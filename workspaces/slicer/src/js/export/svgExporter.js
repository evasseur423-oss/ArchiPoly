/**
 * Production-Ready SVG Exporter for Laser Cutters and Vector CAD
 * Maquette Slicer Studio
 */

export class SvgExporter {
  /**
   * Export all sheets or a single sheet to vector SVG format.
   * @param {Object} packedResult - Output from SheetPacker.packLayers
   * @param {Object} [options]
   * @param {number} [options.singleSheetIndex=-1] - If >= 0, export only that sheet; otherwise all side-by-side
   * @param {string} [options.cutColor='#ff0000'] - Laser cut line color (default red)
   * @param {string} [options.guideColor='#0066ff'] - Alignment guide color (default blue)
   * @param {string} [options.labelColor='#111111'] - Text label color
   * @returns {string} Clean SVG XML content
   */
  static generateSVG(packedResult, options = {}) {
    if (!packedResult || !packedResult.sheets || packedResult.sheets.length === 0) {
      throw new Error("Aucune planche à exporter.");
    }

    const {
      singleSheetIndex = -1,
      cutColor = '#ff0000',
      guideColor = '#0066ff',
      labelColor = '#111111'
    } = options;

    const sheetsToExport = singleSheetIndex >= 0
      ? [packedResult.sheets[singleSheetIndex]]
      : packedResult.sheets;

    const sheetSpacing = 30; // 30 mm between sheets when exported together
    const totalSheets = sheetsToExport.length;
    const sheetW = packedResult.sheetWidth;
    const sheetH = packedResult.sheetHeight;

    // Arrange sheets side by side horizontally
    const totalWidth = totalSheets * sheetW + (totalSheets - 1) * sheetSpacing;
    const totalHeight = sheetH;

    let svg = `<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n`;
    svg += `<!-- Generated by Maquette Slicer Studio - Architectural Fabrication -->\n`;
    svg += `<svg xmlns="http://www.w3.org/2000/svg"\n`;
    svg += `     xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape"\n`;
    svg += `     width="${totalWidth.toFixed(2)}mm"\n`;
    svg += `     height="${totalHeight.toFixed(2)}mm"\n`;
    svg += `     viewBox="0 0 ${totalWidth.toFixed(2)} ${totalHeight.toFixed(2)}">\n`;

    // Metadata & Style Definitions
    svg += `  <defs>\n`;
    svg += `    <style type="text/css">\n`;
    svg += `      .cut-line { stroke: ${cutColor}; stroke-width: 0.1mm; fill: none; stroke-linecap: round; stroke-linejoin: round; }\n`;
    svg += `      .guide-line { stroke: ${guideColor}; stroke-width: 0.1mm; stroke-dasharray: 2 2; fill: none; stroke-linecap: round; }\n`;
    svg += `      .sheet-border { stroke: #888888; stroke-width: 0.2mm; fill: none; }\n`;
    svg += `      .label-text { font-family: 'JetBrains Mono', 'Courier New', monospace; font-size: 3.5mm; fill: ${labelColor}; font-weight: bold; }\n`;
    svg += `      .sub-text { font-family: 'JetBrains Mono', 'Courier New', monospace; font-size: 2.0mm; fill: #555555; }\n`;
    svg += `    </style>\n`;
    svg += `  </defs>\n\n`;

    for (let sIdx = 0; sIdx < sheetsToExport.length; sIdx++) {
      const sheet = sheetsToExport[sIdx];
      const sheetOffsetX = sIdx * (sheetW + sheetSpacing);

      svg += `  <!-- ================= SHEET ${sheet.sheetNumber} ================= -->\n`;
      svg += `  <g id="SHEET_${sheet.sheetNumber}" transform="translate(${sheetOffsetX.toFixed(2)}, 0)">\n`;

      // 1. Layer: SHEET_BORDER
      svg += `    <g id="SHEET_BORDER_${sheet.sheetNumber}" inkscape:groupmode="layer" inkscape:label="00_SHEET_BORDER">\n`;
      svg += `      <rect class="sheet-border" x="0" y="0" width="${sheet.width.toFixed(2)}" height="${sheet.height.toFixed(2)}" />\n`;
      svg += `      <text x="8" y="6" class="sub-text">PLANCHE ${sheet.sheetNumber}/${totalSheets} - ${sheet.width}x${sheet.height}mm - MAQUETTE SLICER STUDIO</text>\n`;
      svg += `    </g>\n\n`;

      // 2. Layer: ALIGNMENT_GUIDES (Blue dashed lines from layer N+1 onto layer N)
      svg += `    <g id="ALIGNMENT_GUIDES_${sheet.sheetNumber}" inkscape:groupmode="layer" inkscape:label="01_ALIGNMENT_GUIDES">\n`;
      for (const item of sheet.items) {
        if (item.guides && item.guides.length > 0) {
          for (const guide of item.guides) {
            if (guide.outer && guide.outer.length >= 3) {
              svg += `      <path class="guide-line" d="${this.pointsToSvgPath(guide.outer)}" />\n`;
            }
            for (const hole of guide.holes) {
              if (hole.length >= 3) {
                svg += `      <path class="guide-line" d="${this.pointsToSvgPath(hole)}" />\n`;
              }
            }
          }
        }
      }
      svg += `    </g>\n\n`;

      // 3. Layer: LABELS & NUMBERING (Engraving / Text layer)
      svg += `    <g id="LABELS_${sheet.sheetNumber}" inkscape:groupmode="layer" inkscape:label="02_LABELS">\n`;
      for (const item of sheet.items) {
        if (item.centroid) {
          const [cx, cy] = item.centroid;
          // Crosshair alignment marker
          svg += `      <path stroke="${labelColor}" stroke-width="0.1mm" d="M ${(cx - 2).toFixed(2)},${cy.toFixed(2)} L ${(cx + 2).toFixed(2)},${cy.toFixed(2)} M ${cx.toFixed(2)},${(cy - 2).toFixed(2)} L ${cx.toFixed(2)},${(cy + 2).toFixed(2)}" />\n`;
          // Stratum label
          svg += `      <text x="${cx.toFixed(2)}" y="${(cy - 1.5).toFixed(2)}" text-anchor="middle" class="label-text">${item.label}</text>\n`;
          svg += `      <text x="${cx.toFixed(2)}" y="${(cy + 4.5).toFixed(2)}" text-anchor="middle" class="sub-text">+${item.elevationMm.toFixed(1)}mm</text>\n`;
        }
      }
      svg += `    </g>\n\n`;

      // 4. Layer: CUT_LINES (Continuous Laser Cut Red Line)
      svg += `    <g id="CUT_LINES_${sheet.sheetNumber}" inkscape:groupmode="layer" inkscape:label="03_CUT_LINES">\n`;
      for (const item of sheet.items) {
        if (item.outer && item.outer.length >= 3) {
          svg += `      <path class="cut-line" d="${this.pointsToSvgPath(item.outer)}" />\n`;
        }
        for (const hole of item.holes) {
          if (hole.length >= 3) {
            svg += `      <path class="cut-line" d="${this.pointsToSvgPath(hole)}" />\n`;
          }
        }
      }
      svg += `    </g>\n`;

      svg += `  </g>\n\n`;
    }

    svg += `</svg>\n`;
    return svg;
  }

  static pointsToSvgPath(points) {
    if (!points || points.length === 0) return '';
    let d = `M ${points[0][0].toFixed(2)},${points[0][1].toFixed(2)}`;
    for (let i = 1; i < points.length; i++) {
      d += ` L ${points[i][0].toFixed(2)},${points[i][1].toFixed(2)}`;
    }
    d += ` Z`;
    return d;
  }
}
